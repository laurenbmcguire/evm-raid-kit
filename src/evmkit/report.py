"""Executive one-page status report (Markdown) and rule-based headline / decisions."""

from __future__ import annotations


def money(v: float | None, short: bool = False) -> str:
    if v is None:
        return "n/a"
    sign = "-" if v < 0 else ""
    a = abs(v)
    if short:
        if a >= 1e6:
            return f"{sign}${a / 1e6:.2f}M"
        if a >= 1e3:
            return f"{sign}${a / 1e3:.1f}k"
        return f"{sign}${a:,.0f}"
    return f"{sign}${a:,.0f}"


def ratio(v: float | None) -> str:
    return "n/a" if v is None else f"{v:.2f}"


def pct(v: float | None) -> str:
    return "n/a" if v is None else f"{v:.1%}"


def headline(s: dict) -> str:
    e, es, r = s["evm"], s["earned_schedule"], s["rag"]
    over = -e["vac"]
    cost = (
        f"CPI {e['cpi']:.2f} forecasts {money(e['eac_cpi'], True)} at completion, "
        f"{money(over, True)} ({-e['vac_pct']:.1%}) over the {money(e['bac'], True)} budget"
        if over > 0 else
        f"CPI {e['cpi']:.2f} forecasts {money(e['eac_cpi'], True)} at completion, within the "
        f"{money(e['bac'], True)} budget"
    )
    slip = es["slip_working_days"]
    sched = (
        f"earned schedule (SPI(t) {es['spi_t']:.2f}) forecasts finish on {es['forecast_finish']}, "
        f"{slip} working days after the {es['planned_finish']} baseline"
        if slip > 0 else
        f"earned schedule (SPI(t) {es['spi_t']:.2f}) forecasts finish on {es['forecast_finish']}, "
        f"on or ahead of the {es['planned_finish']} baseline"
    )
    return (
        f"Overall {r['overall'].upper()}. {pct(e['pct_complete'])} complete against "
        f"{pct(e['pct_planned'])} planned. {cost}; {sched}."
    )


def decisions(s: dict) -> list[str]:
    """Rule-based 'decisions needed' list, most material first (max 5)."""
    e, es, c, rd = s["evm"], s["earned_schedule"], s["cpm"], s["raid"]
    out: list[str] = []
    if e["vac"] < 0:
        line = (
            f"**Funding:** forecast overrun of {money(-e['vac'], True)} ({-e['vac_pct']:.1%} of BAC; "
            f"EAC range {money(min(e['eac_atypical'], e['eac_cpi']), True)} to "
            f"{money(max(e['eac_cpi'], e['eac_cpi_spi']), True)}). Decide between releasing "
            f"contingency and descoping."
        )
        if e["tcpi_bac"] and e["tcpi_bac"] > 1.05:
            line += (f" Finishing on budget needs TCPI {e['tcpi_bac']:.2f} against a CPI of "
                     f"{e['cpi']:.2f} to date, so a controlled re-baseline is the realistic path.")
        out.append(line)
    if es["slip_working_days"] > 0:
        ids = ", ".join(t["id"] for t in c["critical_tasks_behind"]) or "none flagged"
        out.append(
            f"**Schedule:** accept a forecast finish of {es['forecast_finish']} "
            f"(+{es['slip_working_days']} working days) or approve recovery on critical-path work "
            f"behind plan ({ids})."
        )
    for r in rd["top_risks"]:
        if r["score"] >= 15:
            out.append(f"**Risk {r['id']}** (score {r['score']}, {r['owner']}): confirm mitigation "
                       f"funding and date. {r['description']}.")
    if rd["overdue_count"]:
        owners = sorted({i["owner"] for i in rd["overdue_items"]})
        out.append(f"**RAID hygiene:** {rd['overdue_count']} open item(s) past due; "
                   f"{', '.join(owners)} to re-plan or close them before the next report.")
    return out[:5]


def _rag_cell(v: str) -> str:
    return f"**{v.upper()}**"


def render_markdown(s: dict) -> str:
    e, es, c, rd, r = s["evm"], s["earned_schedule"], s["cpm"], s["raid"], s["rag"]
    lines: list[str] = []
    a = lines.append
    a(f"# Executive status report: {s['project']}")
    a("")
    a(f"Status date **{s['status_date']}** | Overall **{r['overall'].upper()}** | "
      f"Generated by evmkit from synthetic sample data")
    a("")
    a(f"> {s['headline']}")
    a("")
    a("## RAG")
    a("")
    a("| Scope | Schedule | Cost | Risk |")
    a("|---|---|---|---|")
    a("| " + " | ".join(_rag_cell(r[k]) for k in ("scope", "schedule", "cost", "risk")) + " |")
    a("| " + " | ".join(r["reasons"][k] for k in ("scope", "schedule", "cost", "risk")) + " |")
    a("")
    a("## Key metrics")
    a("")
    a("| Metric | Value | Metric | Value |")
    a("|---|---:|---|---:|")
    pairs = [
        ("BAC", money(e["bac"]), "CPI", ratio(e["cpi"])),
        ("PV (planned value)", money(e["pv"]), "SPI", ratio(e["spi"])),
        ("EV (earned value)", money(e["ev"]), "SPI(t) earned schedule", ratio(es["spi_t"])),
        ("AC (actual cost)", money(e["ac"]), "ES / AT (working days)",
         f"{es['es_days']:.1f} / {es['at_days']:.0f}"),
        ("SV", money(e["sv"]), "CV", money(e["cv"])),
        ("EAC = BAC/CPI", money(e["eac_cpi"]), "ETC", money(e["etc"])),
        ("EAC = AC+(BAC-EV)", money(e["eac_atypical"]), "VAC", f"{money(e['vac'])} ({pct(e['vac_pct'])})"),
        ("EAC = AC+(BAC-EV)/(CPI*SPI)", money(e["eac_cpi_spi"]), "TCPI to BAC", ratio(e["tcpi_bac"])),
        ("Baseline finish", es["planned_finish"], "Forecast finish (ES)",
         f"{es['forecast_finish']} ({es['slip_working_days']:+d} wd)"),
    ]
    for p in pairs:
        a(f"| {p[0]} | {p[1]} | {p[2]} | {p[3]} |")
    a("")
    a("## Top risks")
    a("")
    a("| ID | Risk | Owner | P | I | Score | Due |")
    a("|---|---|---|:-:|:-:|:-:|---|")
    for x in rd["top_risks"]:
        a(f"| {x['id']} | {x['description']} | {x['owner']} | {x['probability']} | {x['impact']} | "
          f"{x['score']} ({x['heat']}) | {x['due']} |")
    a("")
    a("## Decisions needed")
    a("")
    for i, d in enumerate(s["decisions"], 1):
        a(f"{i}. {d}")
    if not s["decisions"]:
        a("None this period.")
    a("")
    a("## Watch list")
    a("")
    crit = ", ".join(f"{t['id']} {t['name']} (SV {money(t['sv'], True)})" for t in c["critical_tasks_behind"])
    a(f"- **Critical path** ({c['critical_count']} tasks, {c['duration_working_days']} working days): "
      f"{' > '.join(c['critical_path'])}. Behind plan: {crit or 'none'}.")
    od = "; ".join(f"{i['id']} ({i['owner']}, {i['days_overdue']} d)" for i in rd["overdue_items"])
    a(f"- **Overdue RAID items** ({rd['overdue_count']}): {od or 'none'}.")
    owners = ", ".join(f"{k} {v}" for k, v in rd["issues_by_owner"].items())
    a(f"- **Open issues by owner:** {owners or 'none'}. Open RAID items: {rd['open_total']} "
      f"(mean age {rd['mean_open_age_days']:.0f} days).")
    if s.get("reconciliation"):
        rc = s["reconciliation"]
        a(f"- **Data check:** plan.csv AC {money(rc['plan_ac_total'])} vs timesheets "
          f"{money(rc['timesheet_ac_total'])} (max task difference {money(rc['max_task_abs_diff'])}).")
    a("")
    a(f"<sub>Progress source: {s['progress_source']}. PV uses a linear spread of each task's budget over "
      f"its planned working days. All figures come from synthetic sample data.</sub>")
    a("")
    return "\n".join(lines)
